<?php

namespace PiShift\Content\Console;

use Illuminate\Console\Command;
use Illuminate\Filesystem\Filesystem;
use Illuminate\Support\Str;
use PiShift\Content\Collections\CollectionRegistry;
use PiShift\Content\Fields\Field;
use PiShift\Content\Fields\Repeater;
use PiShift\Content\Globals\GlobalRegistry;
use PiShift\Content\Sections\SectionRegistry;

/**
 * TypeScript types of the resolved data each section, global and collection gives its view,
 * for sites that render content with React instead of Blade.
 *
 * @internal Not part of the public API; may change in any release.
 */
class TypesCommand extends Command
{
    protected $signature = 'content:types {--path= : Output file (default resources/js/types/content.d.ts)}';

    protected $description = 'Generate TypeScript types from the section, global and collection schemas';

    public function handle(Filesystem $files, SectionRegistry $sections, GlobalRegistry $globals, CollectionRegistry $collections): int
    {
        $path = $this->option('path') ?: resource_path('js/types/content.d.ts');

        $out = [
            '// Generated by `php artisan content:types`. Do not edit: change the PHP types and run it again.',
            '',
            'export interface ContentFile { url: string; name: string; mime: string | null; size: number | null }',
            'export interface ContentImage { url: string; alt: string; width: number | null; height: number | null }',
            'export interface ContentLink { url: string; label: string | null; new_tab: boolean }',
            '',
        ];

        $sectionNames = [];

        foreach ($sections->all() as $type) {
            $name = Str::studly($type->key()).'Section';
            $sectionNames[$type->key()] = $name;
            $out[] = "/** {$type->label()} (version {$type->version()}) */";
            $out[] = $this->interface($name, $type->fields());
        }

        foreach ($globals->all() as $type) {
            $out[] = "/** {$type->label()} */";
            $out[] = $this->interface(Str::studly($type->key()).'Global', $type->fields());
        }

        foreach ($collections->all() as $type) {
            $out[] = "/** {$type->label()} */";
            $out[] = $this->interface(Str::studly($type->key()).'Record', $type->fields());
        }

        if ($sectionNames !== []) {
            $out[] = 'export interface SectionTypes {';

            foreach ($sectionNames as $key => $name) {
                $out[] = "    '{$key}': {$name};";
            }

            $out[] = '}';
            $out[] = '';
        }

        $files->ensureDirectoryExists(dirname($path));
        $files->put($path, implode("\n", $out));

        $this->components->info("Types written to {$path}");

        return self::SUCCESS;
    }

    /**
     * @param  list<Field>  $fields
     */
    protected function interface(string $name, array $fields): string
    {
        return "export interface {$name} {\n".$this->properties($fields, 1)."}\n";
    }

    /**
     * @param  list<Field>  $fields
     */
    protected function properties(array $fields, int $depth): string
    {
        $indent = str_repeat('    ', $depth);
        $lines = '';

        foreach ($fields as $field) {
            // Toggles resolve to a boolean and repeaters to a list, never null.
            $optional = $field->isRequired() || in_array($field->type(), ['toggle', 'repeater'], true) ? '' : ' | null';
            $lines .= "{$indent}{$field->getName()}: {$this->type($field, $depth)}{$optional};\n";
        }

        return $lines;
    }

    protected function type(Field $field, int $depth): string
    {
        $schema = $field->toSchema();

        return match ($field->type()) {
            'text', 'textarea', 'rich-text', 'color', 'icon', 'upload' => 'string',
            'number' => 'number',
            'toggle' => 'boolean',
            'date', 'datetime' => 'string',
            'select' => $this->selectType(array_keys($schema['options'] ?? [])),
            'link' => 'ContentLink',
            'image' => 'ContentImage',
            'file' => 'ContentFile',
            'repeater' => $field instanceof Repeater
                ? "Array<{\n".str_repeat('    ', $depth + 1)."_id: string;\n".$this->properties($field->getFields(), $depth + 1).str_repeat('    ', $depth).'}>'
                : 'unknown[]',
            default => 'unknown',
        };
    }

    /**
     * A union of fixed option keys; options loaded from the database (ids) stay a string.
     *
     * @param  list<string|int>  $keys
     */
    protected function selectType(array $keys): string
    {
        if ($keys === [] || count($keys) > 30 || collect($keys)->contains(fn (string|int $key): bool => is_int($key) || ctype_digit($key))) {
            return 'string';
        }

        return implode(' | ', array_map(fn (string $key): string => "'".addslashes($key)."'", $keys));
    }
}
